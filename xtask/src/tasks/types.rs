pub fn run(sh: &Shell) -> xshell::Result<()> {
    sh.write_file(output(), typescript())
}

fn output() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../web/src/api/types.gen.ts")
}

fn typescript() -> String {
    // serde writes i64/u64 as JSON numbers, and JSON.parse never yields a bigint.
    let cfg = ts_rs::Config::from_env().with_large_int("number");
    let mut out = String::from("// Generated by `cargo xtask types`. Do not edit.\n\n");
    macro_rules! emit {
        ($($ty:ty),+ $(,)?) => {
            $(
                out.push_str("export ");
                out.push_str(&<$ty as TS>::decl(&cfg));
                out.push_str("\n\n");
            )+
        };
    }
    emit!(
        AuthUser,
        AuthMe,
        Privilege,
        ClusterGrant,
        Identity,
        LaneHealth,
        ClusterHealth,
        CleanupPolicy,
        TopicRow,
        PartitionRow,
        TopicDetail,
        CreateTopic,
        AddPartitions,
        GroupState,
        MemberAssignment,
        GroupMember,
        GroupOffset,
        GroupRow,
        GroupDetail,
        ResetTarget,
        ResetOffsets,
        OffsetMove,
        TopicGroupRow,
        LogDir,
        BrokerRow,
        ConfigSource,
        ConfigEntry,
        EditConfigs,
        SchemaType,
        SchemaCompatibility,
        SubjectVersion,
        SubjectRow,
        SubjectRowsResult,
        SchemaReference,
        SubjectDetail,
        RegisterSchema,
        RegisteredVersion,
        EditSubject,
        AclStatus,
        AclResourceType,
        AclPatternType,
        AclOperation,
        AclPermission,
        Acl,
        AclListing,
        CreateAcls,
        QuotaStatus,
        QuotaEntityType,
        QuotaEntity,
        ClientQuota,
        QuotaListing,
        ScramStatus,
        ScramMechanism,
        ScramCredential,
        ScramUser,
        ScramListing,
        SetScramCredential,
        RecordOrder,
        RecordHeader,
        Record,
        RecordPage,
        RecordLookup,
        RecordPayload,
        ProduceRecord,
        ProducedRecord,
        TailStart,
        TailEvent,
        SearchKind,
        SearchHit,
        TopicRate,
        Update,
    );
    out
}

#[cfg(test)]
mod tests {
    use super::{output, typescript};

    #[test]
    fn generated_typescript_is_checked_in() {
        let actual = std::fs::read_to_string(output()).unwrap_or_default();

        assert_eq!(
            actual,
            typescript(),
            "frontend types are stale; run `cargo xtask types`"
        );
    }
}
